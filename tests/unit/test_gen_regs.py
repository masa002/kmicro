"""tools/gen_regs.py on a CMSIS-style header written here: register addresses from struct layouts and instance macros,
bit constants, IRQ numbers, a board pin map, and only the names the Kotlin sources use; then on C that such headers
also hold: array sizes from macros and divisions, struct tags, two registers in one declaration, octal and
floating-point constants, ports after GPIOH, and the warnings for what is left out. No compiler needed
(tests/run_all.py's irq test compiles a generated file).

python -m unittest discover -s tests/unit
"""
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

HEADER = '''/* a device header in the CMSIS style */
#define __IO volatile
#define __I  volatile const
#define PERIPH_BASE           (0x40000000UL)
#define AHB2PERIPH_BASE       (PERIPH_BASE + 0x08000000UL)
#define GPIOA_BASE            (AHB2PERIPH_BASE + 0x0000UL)
#define GPIOB_BASE            (AHB2PERIPH_BASE + 0x0400UL)

typedef struct {
  __IO uint32_t MODER;        /* 0x00 */
  __IO uint16_t OTYPER;       /* 0x04 */
  uint16_t      RESERVED0;    /* 0x06 */
  __IO uint32_t AFR[2];       /* 0x08 */
  __I  uint8_t  ID;           /* 0x10 */
  __IO uint32_t BSRR;         /* 0x14, after padding */
} GPIO_TypeDef;

#define GPIOA               ((GPIO_TypeDef *) GPIOA_BASE)
#define GPIOB               ((GPIO_TypeDef *) GPIOB_BASE)

#define GPIO_MODER_MODE1_Pos  (2U)
#define GPIO_MODER_MODE1_Msk  (0x3UL << GPIO_MODER_MODE1_Pos)
#define GPIO_MODER_MODE1      GPIO_MODER_MODE1_Msk

typedef enum {
  SysTick_IRQn = -1,
  EXTI0_IRQn = 6,
} IRQn_Type;
'''
BOARD = '#define LED_PORT GPIOB\n#define LED_PIN 3u\n'
APP = '''package board
fun on() = hw_wr32(GPIOA.BSRR, GPIO_MODER_MODE1_Msk or LED_PIN.toUInt()) + EXTI0_IRQn + GPIO_MODER_MODE1_Pos
'''
OLD = '// Generated by kmicro tools/gen_regs.py from old.h. Do not edit.\ninternal object GPIOB {}\n'


class GenRegs(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.d = Path(self.tmp.name)
        (self.d / 'device.h').write_text(HEADER, encoding='utf-8')
        (self.d / 'board.h').write_text(BOARD, encoding='utf-8')
        (self.d / 'src/sub').mkdir(parents=True)
        (self.d / 'src/sub/app.kt').write_text(APP, encoding='utf-8')
        (self.d / 'src/OldRegs.kt').write_text(OLD, encoding='utf-8')     # generated: its names do not count

    def tearDown(self):
        self.tmp.cleanup()

    def gen(self, *args):
        out = self.d / 'new/folder/Regs.kt'
        r = subprocess.run([sys.executable, str(ROOT / 'tools/gen_regs.py'), '--header', str(self.d / 'device.h'),
                            '--out', str(out), '--package', 'board', *map(str, args)], capture_output=True, text=True)
        return r, (out.read_text(encoding='utf-8').splitlines() if out.exists() else [])

    def test_used_names_only(self):
        r, lines = self.gen('--sources', self.d / 'src', '--pins', self.d / 'board.h')
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(lines[0], '// Generated by kmicro tools/gen_regs.py from device.h and board.h. Do not edit.')
        self.assertIn('package board', lines)
        gpioa = lines[lines.index('internal object GPIOA {'):]
        self.assertEqual(gpioa[:7], ['internal object GPIOA {',
                                     '    const val BASE: UInt = 0x48000000u',
                                     '    const val MODER: UInt = 0x48000000u',
                                     '    const val OTYPER: UInt = 0x48000004u',
                                     '    const val AFR: UInt = 0x48000008u   // [2] x 4 B',
                                     '    const val ID: UInt = 0x48000010u',
                                     '    const val BSRR: UInt = 0x48000014u'])
        self.assertEqual(gpioa[7], '}')
        self.assertNotIn('internal object GPIOB {', lines)
        for line in ['internal const val GPIO_MODER_MODE1_Msk: UInt = 0xCu',
                     'internal const val GPIO_MODER_MODE1_Pos: Int = 2',
                     'internal const val EXTI0_IRQn: Int = 6',
                     'internal const val LED_PORT: UInt = 0x48000400u   // GPIOB',
                     'internal const val LED_PIN: Int = 3']:
            self.assertIn(line, lines)
        self.assertFalse(any('GPIO_MODER_MODE1:' in line or 'SysTick_IRQn' in line for line in lines))
        self.assertIn('Regs.kt: 2 peripherals, 5 registers, 2 constants, 2 IRQ numbers', r.stdout)

    def test_all(self):
        r, lines = self.gen('--all')
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn('internal object GPIOB {', lines)
        self.assertIn('    const val BSRR: UInt = 0x48000414u', lines)
        self.assertIn('internal const val GPIO_MODER_MODE1: UInt = 0xCu', lines)
        self.assertIn('internal const val SysTick_IRQn: Int = -1', lines)

    def more(self, text):
        """The options for a second header, read after device.h."""
        (self.d / 'more.h').write_text(text, encoding='utf-8')
        return '--header', self.d / 'more.h'

    def test_array_sizes_from_a_macro_and_a_division(self):
        r, lines = self.gen('--all', *self.more("""#define DMA_CHANNELS 4U
typedef struct
{
  __IO uint32_t CTRL;
  __IO uint32_t CH[DMA_CHANNELS];
  uint32_t      RESERVED0[(0x20 - 0x14) / 4];
  __IO uint32_t STATUS;
} DMA_TypeDef;
#define DMA1_BASE 0x40020000UL
#define DMA1      ((DMA_TypeDef *) DMA1_BASE)
"""))
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn('    const val CH: UInt = 0x40020004u   // [4] x 4 B', lines)
        self.assertIn('    const val STATUS: UInt = 0x40020020u', lines)

    def test_struct_tag_and_several_declarators(self):
        r, lines = self.gen('--all', *self.more("""typedef struct tim
{
  __IO uint32_t CR1, CR2[2];
  __IO uint16_t SR, DIER;
  __IO uint32_t CNT;
} TIM_TypeDef;
#define TIM2      ((TIM_TypeDef *) PERIPH_BASE)
"""))
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(lines[lines.index('internal object TIM2 {'):][1:7],
                         ['    const val BASE: UInt = 0x40000000u',
                          '    const val CR1: UInt = 0x40000000u',
                          '    const val CR2: UInt = 0x40000004u   // [2] x 4 B',
                          '    const val SR: UInt = 0x4000000Cu',
                          '    const val DIER: UInt = 0x4000000Eu',
                          '    const val CNT: UInt = 0x40000010u'])

    def test_c_integer_constants(self):
        r, lines = self.gen('--all', *self.more('#define MODE_MASK  017\n#define HALF_RANGE (0x100 / 2)\n'
                                                '#define LOW_BITS   (0x107 % 8)\n#define HSE_VALUE  8e6\n'
                                                '#define RATIO      1.5\n#define NO_OCTAL   08\n'
                                                '#define NO_VALUE   (1 / 0)\n'))
        self.assertEqual(r.returncode, 0, r.stderr)
        for line in ['internal const val MODE_MASK: UInt = 0xFu', 'internal const val HALF_RANGE: UInt = 0x80u',
                     'internal const val LOW_BITS: UInt = 0x7u']:
            self.assertIn(line, lines)
        for name in ('HSE_VALUE', 'RATIO', 'NO_OCTAL', 'NO_VALUE'):        # no integers: left out
            self.assertFalse(any(name in line for line in lines), name)

    def test_pin_map_ports_and_pin_expressions(self):
        more = self.more('#define GPIOI_BASE (AHB2PERIPH_BASE + 0x2000UL)\n'
                         '#define GPIOI      ((GPIO_TypeDef *) GPIOI_BASE)\n')
        board = self.d / 'board.h'
        board.write_bytes(b'#define BTN_PORT GPIOI   /* 5 \xb5s */\n#define BTN_PIN  (1u + 10u)\n')
        r, lines = self.gen('--all', '--pins', board, *more)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn('internal const val BTN_PORT: UInt = 0x48002000u   // GPIOI', lines)
        self.assertIn('internal const val BTN_PIN: Int = 11', lines)
        for text, message in (('#define BTN_PORT GPIOK\n#define BTN_PIN 1\n',
                               'BTN_PORT is GPIOK, which the headers do not define'),
                              ('#define BTN_PORT GPIOA\n#define BTN_PIN PIN_B\n', 'BTN_PIN is not a pin number'),
                              ('#define BTN_PORT GPIOA\n', 'BTN_PIN is not a pin number')):
            board.write_text(text, encoding='utf-8')
            r, _ = self.gen('--all', '--pins', board, *more)
            self.assertEqual((r.returncode, r.stderr), (1, f'gen_regs: {board}: {message}\n'))

    def test_names_left_out_are_named(self):
        r, _ = self.gen('--sources', self.d / 'src')
        self.assertEqual((r.returncode, r.stderr), (0, ''))
        more = self.more("""/* what gen_regs.py does not read:
   a bit field, a union */
typedef struct
{
  __IO uint32_t CR1 : 4;
  __IO uint32_t SR;
} SPI_TypeDef;
typedef struct
{
  union { __IO uint32_t CR; __IO uint16_t CR16; } U;
  __IO uint32_t CNT;
} TIM_TypeDef;
#define SPI1       ((SPI_TypeDef *) PERIPH_BASE)
#define TIM2       ((TIM_TypeDef *) PERIPH_BASE)
#define UART4      ((USART_TypeDef *) PERIPH_BASE)
#define GPIOI      ((GPIO_TypeDef *) GPIOI_BASE)
#define HSE_VALUE  8e6
#define LSE_VALUE  32768.0
""")
        (self.d / 'src/more.kt').write_text('fun more() = SPI1.SR + TIM2.CNT + UART4.DR + GPIOI.MODER + HSE_VALUE\n',
                                            encoding='utf-8')
        r, lines = self.gen('--sources', self.d / 'src', *more)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(r.stderr.splitlines(), [
            'gen_regs: warning: GPIOI left out: its address GPIOI_BASE is no integer constant, at more.h line 16',
            'gen_regs: warning: HSE_VALUE left out: 8e6 is no integer constant, at more.h line 17',
            'gen_regs: warning: SPI1 left out: struct SPI_TypeDef not understood at more.h line 3: uint32_t CR1 : 4',
            'gen_regs: warning: TIM2 left out: struct TIM_TypeDef not understood at more.h line 8: union { uint32_t CR',
            'gen_regs: warning: UART4 left out: no struct USART_TypeDef found in the headers'])
        self.assertIn('internal object GPIOA {', lines)
        r, _ = self.gen('--all', *more)                                    # nobody asked for LSE_VALUE
        self.assertEqual((r.returncode, r.stderr), (0, ''))

    def test_missing_inputs_are_one_line_errors(self):
        r, _ = self.gen('--sources', self.d / 'nowhere')
        self.assertEqual(r.returncode, 2)
        self.assertIn('no such folder', r.stderr)
        r, _ = self.gen('--pins', self.d / 'nope.h')
        self.assertEqual(r.returncode, 2)
        self.assertIn('nope.h: no such file', r.stderr)


if __name__ == '__main__':
    unittest.main()
