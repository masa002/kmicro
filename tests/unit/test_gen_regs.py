"""tools/gen_regs.py on a CMSIS-style header written here: register addresses from struct layouts and instance macros,
bit constants, IRQ numbers, a board pin map, and only the names the Kotlin sources use. No compiler needed
(tests/run_all.py's irq test compiles a generated file).

python -m unittest discover -s tests/unit
"""
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

HEADER = '''/* a device header in the CMSIS style */
#define __IO volatile
#define __I  volatile const
#define PERIPH_BASE           (0x40000000UL)
#define AHB2PERIPH_BASE       (PERIPH_BASE + 0x08000000UL)
#define GPIOA_BASE            (AHB2PERIPH_BASE + 0x0000UL)
#define GPIOB_BASE            (AHB2PERIPH_BASE + 0x0400UL)

typedef struct {
  __IO uint32_t MODER;        /* 0x00 */
  __IO uint16_t OTYPER;       /* 0x04 */
  uint16_t      RESERVED0;    /* 0x06 */
  __IO uint32_t AFR[2];       /* 0x08 */
  __I  uint8_t  ID;           /* 0x10 */
  __IO uint32_t BSRR;         /* 0x14, after padding */
} GPIO_TypeDef;

#define GPIOA               ((GPIO_TypeDef *) GPIOA_BASE)
#define GPIOB               ((GPIO_TypeDef *) GPIOB_BASE)

#define GPIO_MODER_MODE1_Pos  (2U)
#define GPIO_MODER_MODE1_Msk  (0x3UL << GPIO_MODER_MODE1_Pos)
#define GPIO_MODER_MODE1      GPIO_MODER_MODE1_Msk

typedef enum {
  SysTick_IRQn = -1,
  EXTI0_IRQn = 6,
} IRQn_Type;
'''
BOARD = '#define LED_PORT GPIOB\n#define LED_PIN 3u\n'
APP = '''package board
fun on() = hw_wr32(GPIOA.BSRR, GPIO_MODER_MODE1_Msk or LED_PIN.toUInt()) + EXTI0_IRQn + GPIO_MODER_MODE1_Pos
'''
OLD = '// Generated by kmicro tools/gen_regs.py from old.h. Do not edit.\ninternal object GPIOB {}\n'


class GenRegs(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.d = Path(self.tmp.name)
        (self.d / 'device.h').write_text(HEADER, encoding='utf-8')
        (self.d / 'board.h').write_text(BOARD, encoding='utf-8')
        (self.d / 'src/sub').mkdir(parents=True)
        (self.d / 'src/sub/app.kt').write_text(APP, encoding='utf-8')
        (self.d / 'src/OldRegs.kt').write_text(OLD, encoding='utf-8')     # generated: its names do not count

    def tearDown(self):
        self.tmp.cleanup()

    def gen(self, *args):
        out = self.d / 'new/folder/Regs.kt'
        r = subprocess.run([sys.executable, str(ROOT / 'tools/gen_regs.py'), '--header', str(self.d / 'device.h'),
                            '--out', str(out), '--package', 'board', *map(str, args)], capture_output=True, text=True)
        return r, (out.read_text(encoding='utf-8').splitlines() if out.exists() else [])

    def test_used_names_only(self):
        r, lines = self.gen('--sources', self.d / 'src', '--pins', self.d / 'board.h')
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(lines[0], '// Generated by kmicro tools/gen_regs.py from device.h and board.h. Do not edit.')
        self.assertIn('package board', lines)
        gpioa = lines[lines.index('internal object GPIOA {'):]
        self.assertEqual(gpioa[:7], ['internal object GPIOA {',
                                     '    const val BASE: UInt = 0x48000000u',
                                     '    const val MODER: UInt = 0x48000000u',
                                     '    const val OTYPER: UInt = 0x48000004u',
                                     '    const val AFR: UInt = 0x48000008u   // [2] x 4 B',
                                     '    const val ID: UInt = 0x48000010u',
                                     '    const val BSRR: UInt = 0x48000014u'])
        self.assertEqual(gpioa[7], '}')
        self.assertNotIn('internal object GPIOB {', lines)
        for line in ['internal const val GPIO_MODER_MODE1_Msk: UInt = 0xCu',
                     'internal const val GPIO_MODER_MODE1_Pos: Int = 2',
                     'internal const val EXTI0_IRQn: Int = 6',
                     'internal const val LED_PORT: UInt = 0x48000400u   // GPIOB',
                     'internal const val LED_PIN: Int = 3']:
            self.assertIn(line, lines)
        self.assertFalse(any('GPIO_MODER_MODE1:' in line or 'SysTick_IRQn' in line for line in lines))
        self.assertIn('Regs.kt: 2 peripherals, 5 registers, 2 constants, 2 IRQ numbers', r.stdout)

    def test_all(self):
        r, lines = self.gen('--all')
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn('internal object GPIOB {', lines)
        self.assertIn('    const val BSRR: UInt = 0x48000414u', lines)
        self.assertIn('internal const val GPIO_MODER_MODE1: UInt = 0xCu', lines)
        self.assertIn('internal const val SysTick_IRQn: Int = -1', lines)

    def test_missing_inputs_are_one_line_errors(self):
        r, _ = self.gen('--sources', self.d / 'nowhere')
        self.assertEqual(r.returncode, 2)
        self.assertIn('no such folder', r.stderr)
        r, _ = self.gen('--pins', self.d / 'nope.h')
        self.assertEqual(r.returncode, 2)
        self.assertIn('nope.h: no such file', r.stderr)


if __name__ == '__main__':
    unittest.main()
